package Operators;

public class RelationalOperators {
    public static void main(String[] args) {
        int a = 10, b = 20;
        System.out.println(a > b); // false
        System.out.println(a < b); // true
        System.out.println(a >= 10); // true
        System.out.println(a <= 9); // false
        System.out.println(a == 10); // true
        System.out.println(a != b); // true
    }
}

// Six operators that compare two values and always produce a boolean : > greater than, < less than, >=
//greater than or equal, <= less than or equal, == equal to, and != not equal to.